export default async ({open,check}) => {
 const s=await open('inspector')
 const f=s.frame
 await f.getByRole('button',{name:'Configuración'}).click()
 await f.getByLabel('Clave de desarrollador').fill('123456')
 await f.getByLabel('Confirmar clave').fill('123456')
 await f.getByRole('button',{name:'Crear clave y entrar'}).click()
 await check('se abre la configuración',async()=>{await f.getByRole('heading',{name:'Parámetros del cálculo'}).waitFor()})
 await f.getByLabel('Efectos personales (kg)').fill('20')
 await f.getByLabel('Nombre',{exact:true}).fill('Artículo de prueba')
 await f.getByLabel('Categoría',{exact:true}).fill('Prueba')
 await f.getByLabel('Valor unitario (USD)').fill('70')
 await f.getByLabel('Límite de cantidad').fill('2')
 await f.getByRole('button',{name:'Añadir artículo'}).click()
 await check('artículo creado',async()=>{await f.getByText('Artículo de prueba',{exact:true}).waitFor()})
 await f.getByRole('button',{name:'Volver al despacho'}).click()
 await f.getByRole('button',{name:'Continuar al equipaje'}).click()
 await f.getByLabel('Cantidad total de bultos').fill('1')
 await f.getByLabel('Peso del bulto 1').fill('30')
 await f.getByLabel('Contenido del bulto 1').fill('Ropa')
 await f.getByLabel('Usar la suma de los pesos de bultos para misceláneas').check()
 await f.getByLabel('Buscar artículos').fill('Artículo de prueba')
 await f.getByRole('button',{name:/Artículo de prueba/}).click()
 await f.getByRole('button',{name:'Ver resumen'}).click()
 await check('configuración y artículo aplicados',async()=>{const t=await f.locator('body').innerText();if(!t.includes('$170.00 USD'))throw new Error('El valor esperado es 170 USD')})
 await s.page.reload()
 await check('bultos y configuración guardados',async()=>{await f.getByRole('button',{name:'Continuar al equipaje'}).click();if(await f.getByLabel('Contenido del bulto 1').inputValue()!=='Ropa')throw new Error('Contenido no guardado');if(!(await f.locator('body').innerText()).includes('20.00 kg'))throw new Error('Configuración no guardada')})
 await f.getByRole('button',{name:'Configuración'}).click()
 await f.getByLabel('Clave de desarrollador').fill('incorrecta')
 await f.getByRole('button',{name:'Desbloquear'}).click()
 await check('clave incorrecta rechazada',async()=>{await f.getByText('Clave incorrecta.').waitFor()})
 await f.getByLabel('Clave de desarrollador').fill('123456')
 await f.getByRole('button',{name:'Desbloquear'}).click()
 await check('acceso con clave guardada',async()=>{await f.getByRole('heading',{name:'Parámetros del cálculo'}).waitFor()})
}
